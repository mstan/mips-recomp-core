"""Generate zero-dispatch language bindings from the common integer encoding schema."""
from pathlib import Path
import argparse,json
root=Path(__file__).resolve().parents[1]
schema=json.loads((root/'isa/integer.json').read_text(encoding='utf-8'))
header='// Generated by tools/generate_integer.py; edit isa/integer.json.\n#pragma once\n'
rust='// Generated by tools/generate_integer.py; edit isa/integer.json.\n'
for group,rows in schema['selectors'].items():
 rust+='pub mod '+group+' {\n'
 for value,name in rows:rust+=' pub const '+name.upper()+': u32 = 0x%02x;\n'%value
 rust+='}\n'
 header+='#define MIPS_COMMON_'+group.upper()+'(X) '+ ' \\\n'.join('X(0x%02x, %s, "%s")'%(value,name,name.upper()) for value,name in rows)+'\n'
 for option in [False,True]:
  macro='mips_'+group+('_option' if option else '')+'_match'
  rust+='#[macro_export]\nmacro_rules! '+macro+' {\n ($value:expr, $op:ident, {$($extension:tt)*}) => { match $value {\n'
  for value,name in rows:rust+='  0x%02x => '%value+('Some($op::'+name+')' if option else '$op::'+name)+',\n'
  rust+='  $($extension)*\n } };\n}\n'
for group,rows in schema['selectors'].items():
 for category in sorted(set(schema['classification'][name] for _,name in rows)):
  selected=[(value,name) for value,name in rows if schema['classification'][name]==category]
  header+='#define MIPS_'+group.upper()+'_'+category.upper()+'(X) '+ ' \\\n'.join('X(0x%02x, %s)'%(value,name) for value,name in selected)+'\n'
for label,selected in [('control',[n for n,c in schema['control'].items() if c in ('branch','call','jump','jump_register','call_register')]),('jump',[n for n,c in schema['control'].items() if c in ('jump','jump_register','call_register') or n=='Jal']),('direct_call',[n for n,c in schema['control'].items() if c=='call'])]:
 rust+='#[macro_export]\nmacro_rules! mips_common_'+label+' {\n ($value:expr, $op:ident; $($extensions:pat_param)|*) => { matches!($value, '
 rust+=' | '.join('$op::'+n for n in selected)+' $(|$extensions)*) };\n}\n'
fields='// Generated by tools/generate_integer.py; edit isa/integer.json.\n#pragma once\n#include <cstdint>\nnamespace mips_recomp::integer {\n'
for name,(shift,width) in schema['fields'].items():
 mask=(1<<width)-1
 fields+='constexpr uint32_t %s(uint32_t word) { return (word >> %du) & 0x%xu; }\n'%(name,shift,mask)
 rust+='#[inline(always)]\npub const fn %s(word: u32) -> u32 { (word >> %d) & 0x%x }\n'%(name,shift,mask)
fields+='}\n'
python='# Generated by tools/generate_integer.py; edit isa/integer.json.\nFIELDS = '+repr(schema['fields'])+'\nSELECTORS = '+repr({name.lower():(group,value) for group,rows in schema['selectors'].items() for value,name in rows})+'\nCONTROL = '+repr({n.lower():c for n,c in schema['control'].items()})+'\n'
outputs={'include/mips_integer_selectors.h':header,'include/mips_fields.h':fields,'bindings/rust/src/selectors.rs':rust,'bindings/python/mips_integer.py':python}
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
for name,text in outputs.items():
 path=root/name
 if args.check:assert path.read_text(encoding='utf-8')==text,name
 else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(text,encoding='utf-8',newline='\n')
